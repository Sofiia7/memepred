/**
 * Regenerates test/RedstoneFixture.sol from live RedStone data.
 *
 *   cd contracts && node scripts/gen-redstone-fixture.mjs
 *
 * The fixture holds real payloads signed by the real authorised signers, so the
 * contract tests exercise genuine signature recovery and the genuine 3-of-5
 * threshold rather than mock signers agreeing with themselves.
 *
 * Note what this script does NOT need: an API key, and RedStone's own SDK. The
 * SDK now refuses to run without an authenticated gateway
 * ("Empty authenticatedGateways array provided"), but the public gateway still
 * serves the signed packages to anyone, and @redstone-finance/protocol turns
 * them into a payload. That is the whole reason this project can be on RedStone
 * instead of paying Pyth $500/month - so if this script ever starts needing a
 * key, that assumption has changed and the migration needs revisiting.
 */
import proto from '@redstone-finance/protocol'
import { writeFileSync } from 'node:fs'

const { SignedDataPackage, RedstonePayload, recoverDeserializedSignerAddress } = proto

/** The five signers hardcoded in PrimaryProdDataServiceConsumerBase. */
const AUTHORISED_SIGNERS = [
  '0x8BB8F32Df04c8b654987DAaeD53D6B6091e3B774',
  '0xdEB22f54738d54976C4c0fe5ce6d408E40d88499',
  '0x51Ce04Be4b3E32572C4Ec9135221d0691Ba7d202',
  '0xDD682daEC5A90dD295d14DA4b0bec9281017b5bE',
  '0x9c5AE89C4Af6aA32cE58588DBaF90d18a855B6de',
].map((a) => a.toLowerCase())

const GATEWAY = 'https://oracle-gateway-1.a.redstone.finance'
const SIGNERS_REQUIRED = 3
const FEEDS = ['PEPE', 'DOGE']

const res = await fetch(`${GATEWAY}/v2/data-packages/latest/redstone-primary-prod`)
if (!res.ok) throw new Error(`gateway responded ${res.status}`)
const all = await res.json()

const fixtures = FEEDS.map((feed) => {
  const packages = all[feed]
  if (!packages) throw new Error(`gateway served no packages for ${feed}`)

  // Recover the signer from the signature rather than trusting the gateway's
  // own signerAddress field, which is exactly what the contract does on-chain.
  const authorised = packages.filter((p) =>
    AUTHORISED_SIGNERS.includes(recoverDeserializedSignerAddress(p).toLowerCase()),
  )
  if (authorised.length < SIGNERS_REQUIRED) {
    throw new Error(`${feed}: only ${authorised.length} authorised signers, need ${SIGNERS_REQUIRED}`)
  }

  const chosen = authorised.slice(0, SIGNERS_REQUIRED)
  const payload = RedstonePayload.prepare(chosen.map((p) => SignedDataPackage.fromObj(p)), '')

  return {
    feed,
    hex: payload.startsWith('0x') ? payload : `0x${payload}`,
    // The oldest of the chosen packages: that is the one the contract's
    // staleness window will be measured against.
    tsMs:  Math.min(...chosen.map((p) => p.timestampMilliseconds)),
    value: chosen[0].dataPoints[0].value,
  }
})

const body = fixtures
  .map((f) => `    // ${f.feed} = $${f.value} at ${new Date(f.tsMs).toISOString()}
    bytes   internal constant ${f.feed}_PAYLOAD      = hex"${f.hex.slice(2)}";
    uint256 internal constant ${f.feed}_TIMESTAMP_MS = ${f.tsMs};
    uint256 internal constant ${f.feed}_VALUE_8DP    = ${Math.round(f.value * 1e8)};`)
  .join('\n\n')

writeFileSync(
  'test/RedstoneFixture.sol',
  `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

/**
 * Real RedStone production payloads, captured from the public gateway.
 *
 * Deliberately real rather than mock-signed: these carry signatures from the
 * actual authorised signers hardcoded in PrimaryProdDataServiceConsumerBase, so
 * a test using them proves our contracts accept live RedStone data - signature
 * recovery, the 3-of-5 threshold and the calldata layout included. Mock signers
 * would prove only that we can talk to ourselves.
 *
 * Generated by scripts/gen-redstone-fixture.mjs. Do not hand-edit.
 */
library RedstoneFixture {
${body}
}
`,
)

for (const f of fixtures) {
  console.log(`${f.feed.padEnd(6)} ${String((f.hex.length - 2) / 2).padStart(4)} bytes  $${f.value}  ts=${f.tsMs}`)
}
console.log('wrote test/RedstoneFixture.sol')
